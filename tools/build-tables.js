// Rebuilds js/tables.js from the Golly .rule files in patterns/golly/rules.
// Usage: node tools/build-tables.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '../patterns/golly/rules');
const out = {};
for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.rule')).sort()) {
  const src = fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r/g, '');
  const sec = name => {
    const lines = src.split('\n'); const out = []; let on = false;
    for (const l of lines) { if (l[0] === '@') { on = l.startsWith('@' + name); continue; } if (on) out.push(l); }
    return out.join('\n');
  };
  const table = sec('TABLE').split('\n').map(l => l.replace(/#.*/, '').trim()).filter(Boolean).join('\n');
  const colors = [];
  for (const l of sec('COLORS').split('\n')) { const m = /^\s*(\d+)\s+(\d+)\s+(\d+)\s+(\d+)\s*(?:#.*)?$/.exec(l); if (m) colors[+m[1]] = [+m[2], +m[3], +m[4]]; }
  for (let i = 0; i < colors.length; i++) if (!colors[i]) colors[i] = null;
  out[f.replace(/\.rule$/, '')] = { table, colors: colors.length ? colors : undefined };
}
const js = `// Named rule tables in Golly's @TABLE format. Rule strings can refer to these by name.
// Generated by tools/build-tables.js from the rule files that ship with Golly
// (golly.sourceforge.io, GPL). See patterns/golly/rules for the originals and their credits.
(function (root) {
  'use strict';
  const CA = root.CA || (root.CA = {});
  CA.TABLES = Object.assign(CA.TABLES || {}, ${JSON.stringify(out, null, 1)});
})(typeof self !== 'undefined' ? self : globalThis);
`;
fs.writeFileSync(path.join(__dirname, '../js/tables.js'), js);
